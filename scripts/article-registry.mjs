import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';

export const projectRoot = fileURLToPath(new URL('../', import.meta.url));
export const articlesRoot = path.join(projectRoot, 'content/articles');

const registryPath = path.join(articlesRoot, 'registry.generated.ts');
const idPattern = /^\s*id:\s*(['"])([a-z0-9]{5})\1\s*,?\s*$/m;

export async function getArticleFolders() {
  const entries = await readdir(articlesRoot, { withFileTypes: true });
  const folders = [];

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    if (!/^[a-z0-9-]+$/.test(entry.name)) {
      throw new Error(`Invalid article folder name: ${entry.name}`);
    }

    const files = await readdir(path.join(articlesRoot, entry.name));
    if (files.includes('index.mdx')) folders.push(entry.name);
  }

  return folders.sort();
}

export async function getArticleIds(folders) {
  const ids = new Set();

  for (const folder of folders) {
    const source = await readFile(
      path.join(articlesRoot, folder, 'index.mdx'),
      'utf8',
    );
    const id = source.match(idPattern)?.[2];

    if (!id)
      throw new Error(`Missing five-character id in ${folder}/index.mdx`);
    if (ids.has(id)) throw new Error(`Duplicate article id: ${id}`);
    ids.add(id);
  }

  return ids;
}

export async function syncRegistry({ check = false } = {}) {
  const folders = await getArticleFolders();
  await getArticleIds(folders);

  const imports = folders.map(
    (folder, index) =>
      `import Article${index}, { article as metadata${index} } from './${folder}/index.mdx';`,
  );
  const entries = folders.map(
    (_, index) =>
      `  { Content: Article${index}, metadata: metadata${index} as ArticleMetadata },`,
  );
  const source = [
    '// Generated by pnpm article:sync. Do not edit by hand.',
    ...imports,
    "import type { ArticleMetadata } from './types';",
    '',
    'export const registeredArticles = [',
    ...entries,
    '] as const;',
    '',
  ].join('\n');
  const formatted = await prettier.format(source, {
    ...(await prettier.resolveConfig(registryPath)),
    filepath: registryPath,
  });

  if (check) {
    const current = await readFile(registryPath, 'utf8').catch(() => '');
    if (current !== formatted) {
      throw new Error(
        'Article registry is out of date. Run pnpm article:sync.',
      );
    }
  } else {
    await writeFile(registryPath, formatted);
  }
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await syncRegistry({ check: process.argv.includes('--check') });
}
